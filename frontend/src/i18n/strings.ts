/** Reason codes like EID_FITR_IN_5_DAYS -> readable chips. */
export function reasonLabel(code: string, lang: Lang): string {
  const m = code.match(/^EID_(FITR|ADHA)_IN_(\d+)_DAYS$/);
  if (m) {
    const name = m[1] === "FITR" ? "Eid-ul-Fitr" : "Eid-ul-Adha";
    return STRINGS[lang].eventIn(eventName(name, lang), Number(m[2]));
  }
  const map: Record<string, [string, string]> = {
    EID_DAY: ["Eid day", "ঈদের দিন"],
    EID_HOLIDAY: ["Eid holiday", "ঈদের ছুটি"],
    SALARY_WINDOW: ["Salary days", "বেতনের দিন"],
    G2P_DISBURSEMENT: ["Allowance disbursement (G2P)", "ভাতা বিতরণ (জিটুপি)"],
    RAMADAN: ["Ramadan", "রমজান"],
    POHELA_BOISHAKH: ["Pohela Boishakh", "পহেলা বৈশাখ"],
    CASH_BELOW_NEED: ["Cash below need", "নগদ চাহিদার চেয়ে কম"],
    EFLOAT_BELOW_NEED: ["E-float below need", "ই-ফ্লোট চাহিদার চেয়ে কম"],
    FLOAT_CAPACITY_SHORT: ["Total float too small", "মোট ফ্লোট যথেষ্ট নয়"],
    RECENT_STOCKOUTS: ["Recent stockouts", "সাম্প্রতিক ঘাটতি"],
  };
  const hit = map[code];
  return hit ? (lang === "bn" ? hit[1] : hit[0]) : code;
}
